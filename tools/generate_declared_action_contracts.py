"""Generate the native action inputs from the shared declarations."""

import argparse
import json
import sys
from difflib import unified_diff
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "Server/src"))

from services.declared_action_contracts import (
    ASSET_MOVE_CONTRACTS,
    ASSET_REFERENCE_FIELDS,
    PREFAB_CHECKPOINT_CONTRACTS,
)

TARGET = ROOT / "MCPForUnity/Editor/Tools/DeclaredActionContracts.generated.cs"


def _fields(names: tuple[str, ...]) -> str:
    return ", ".join(json.dumps(name) for name in names)


def render() -> str:
    assets = "\n".join(
        "        internal const string Asset"
        + "".join(part.title() for part in public.split("_"))
        + f" = {json.dumps(native)};"
        for public, native in ASSET_REFERENCE_FIELDS
    )
    prefabs = "\n".join(
        f"            {{ {json.dumps(action)}, new[] {{ {_fields(('action', *contract.native_required))} }} }},"
        for action, contract in PREFAB_CHECKPOINT_CONTRACTS.items()
    )
    replan = PREFAB_CHECKPOINT_CONTRACTS["replan_prefab"]
    prefab_fields = dict(zip(replan.required, replan.native_required))
    return f"""// <auto-generated />
// Run: python tools/generate_declared_action_contracts.py
using System;
using System.Collections.Generic;
using System.Linq;
using Newtonsoft.Json.Linq;

namespace MCPForUnity.Editor.Tools
{{
    internal static class DeclaredActionContracts
    {{
{assets}
        internal static readonly string[] AssetMoveRequiredFields = {{ {_fields(ASSET_MOVE_CONTRACTS["move"].native_required)} }};
        internal static readonly string[] AssetReferenceFields = {{ {_fields(("action", *(name for _, name in ASSET_REFERENCE_FIELDS)))} }};
        internal const string PrefabCheckpoint = {json.dumps(prefab_fields["operation_id"])};
        internal const string PrefabPreviousCheckpoint = {json.dumps(prefab_fields["previous_operation_id"])};
        internal const string PrefabExpectedObservation = {json.dumps(prefab_fields["expected_observation"])};

        private static readonly Dictionary<string, string[]> PrefabFields = new Dictionary<string, string[]>(StringComparer.Ordinal)
        {{
{prefabs}
        }};

        internal static bool IsPrefabAction(string action) => action != null && PrefabFields.ContainsKey(action);

        internal static bool MatchesPrefabFields(JObject request, string action) =>
            PrefabFields.TryGetValue(action, out var fields)
            && fields.Length == request.Count
            && fields.All(name => request.Property(name) != null);
    }}
}}
"""


def contract_drift(expected: str, actual: str) -> str:
    """Show each changed native field next to its generated declaration."""
    return "".join(
        unified_diff(
            actual.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=TARGET.name,
            tofile=f"generated {TARGET.name}",
            n=0,
        )
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        actual = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        drift = contract_drift(expected, actual)
        if drift:
            print(drift, end="")
            return 1
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Verified declared action inputs in {TARGET.name}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
