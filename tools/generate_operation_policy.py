"""Generate the native arbitration policy from the reviewed server policy catalog."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "Server/src"))

from services.operation_policy import (  # noqa: E402
    CANONICAL_ALIASES,
    CAPABILITY_ALIASES,
    POLICY_RULES,
    POLICY_VERSION,
)

TARGET = ROOT / "MCPForUnity/Editor/Services/ToolOperationPolicy.generated.cs"


def _identifier(value: str) -> str:
    return "".join(part.title() for part in value.split("_"))


def render() -> str:
    """Generate pure metadata and resolution; never import Unity or query job state."""
    aliases = "\n".join(
        f"            {{ {json.dumps(name)}, {json.dumps(source)} }},"
        for name, source in sorted(CANONICAL_ALIASES.items())
    )
    partitions = "\n".join(
        f"            {{ {json.dumps(name)}, new Partition({json.dumps(feature.source)}, new[] {{ "
        + ", ".join(json.dumps(action) for action in feature.native_actions)
        + " }) },"
        for name, feature in sorted(CAPABILITY_ALIASES.items())
    )
    rules = []
    for rule in POLICY_RULES:
        for action in rule.actions or (None,):
            key = rule.command + "\n" + ("0" if action is None else "1" + action)
            reason = (
                "reviewed_control"
                if rule.mode.value == "control"
                else "reviewed_read"
                if rule.mode.value == "shared_read"
                else "reviewed_mutation"
            )
            rules.append(
                f"            {{ {json.dumps(key)}, new ToolOperationPolicy(ToolOperationMode.{_identifier(rule.mode.value)}, "
                f"ToolOperationLifetime.{_identifier(rule.lifetime.value)}, {json.dumps(reason)}) }},"
            )
    return (
        TEMPLATE.replace("@@VERSION@@", str(POLICY_VERSION))
        .replace("@@ALIASES@@", aliases)
        .replace("@@PARTITIONS@@", partitions)
        .replace("@@RULES@@", "\n".join(rules))
    )


TEMPLATE = r"""// <auto-generated />
// Run: python tools/generate_operation_policy.py
using System;
using System.Collections.Generic;
using Newtonsoft.Json.Linq;

namespace MCPForUnity.Editor.Services
{
    internal enum ToolOperationMode { Control, SharedRead, Exclusive }
    internal enum ToolOperationLifetime { Command, TrackedJob, TriggerOnly }

    /// <summary>Effects only. Permissions and actual native job ownership remain separate.</summary>
    internal readonly struct ToolOperationPolicy
    {
        internal const int Version = @@VERSION@@;
        internal ToolOperationMode Mode { get; }
        internal ToolOperationLifetime Lifetime { get; }
        internal string Reason { get; }

        private ToolOperationPolicy(ToolOperationMode mode, ToolOperationLifetime lifetime, string reason)
        {
            Mode = mode;
            Lifetime = lifetime;
            Reason = reason;
        }

        private readonly struct Partition
        {
            internal readonly string Source;
            internal readonly string[] Actions;
            internal Partition(string source, string[] actions) { Source = source; Actions = actions; }
        }

        private static readonly Dictionary<string, string> Aliases = new Dictionary<string, string>(StringComparer.Ordinal)
        {
@@ALIASES@@
        };
        private static readonly Dictionary<string, Partition> Partitions = new Dictionary<string, Partition>(StringComparer.Ordinal)
        {
@@PARTITIONS@@
        };
        private static readonly Dictionary<string, ToolOperationPolicy> Rules = new Dictionary<string, ToolOperationPolicy>(StringComparer.Ordinal)
        {
@@RULES@@
        };

        private static ToolOperationPolicy Exclusive(string reason, ToolOperationLifetime lifetime = ToolOperationLifetime.Command) =>
            new ToolOperationPolicy(ToolOperationMode.Exclusive, lifetime, reason);

        /// <summary>trustedBuiltIn must bind the actual registered handler, never caller JSON or annotations.</summary>
        internal static ToolOperationPolicy Resolve(string commandName, JObject parameters, bool trustedBuiltIn)
        {
            if (!trustedBuiltIn)
                return Exclusive("untrusted_handler");
            if (commandName == null || parameters == null)
                return Exclusive("malformed_operation");
            var token = parameters["action"];
            if (token != null && token.Type != JTokenType.Null && token.Type != JTokenType.String)
                return Exclusive("malformed_action");
            string action = token?.Type == JTokenType.String ? ((string)token).ToLowerInvariant() : null;
            if (Partitions.TryGetValue(commandName, out var partition))
            {
                if (Array.IndexOf(partition.Actions, action) < 0)
                    return Exclusive("unsupported_capability_action");
                commandName = partition.Source;
            }
            if (Aliases.TryGetValue(commandName, out string canonical))
                commandName = canonical;
            if (commandName == "execute_menu_item" || commandName == "execute_code" || commandName == "execute_custom_tool")
                return Exclusive("arbitrary_execution");
            if (commandName == "batch_execute" || commandName == "batch_validate" || commandName == "batch_apply_preview")
                return Exclusive("batch_envelope");
            if (commandName == "manage_ugui" && action == "diagnose_raycast")
            {
                var allow = parameters["allow_custom_filters"];
                if (allow != null && (allow.Type != JTokenType.Boolean || (bool)allow))
                    return Exclusive("conditional_callbacks");
                return new ToolOperationPolicy(ToolOperationMode.SharedRead, ToolOperationLifetime.Command, "reviewed_read");
            }
            if (commandName == "manage_ui" && action == "patch_source")
            {
                var preview = parameters["preview"];
                if (preview == null || preview.Type == JTokenType.Boolean && (bool)preview)
                    return new ToolOperationPolicy(ToolOperationMode.SharedRead, ToolOperationLifetime.Command, "reviewed_preview");
                return Exclusive("conditional_mutation", ToolOperationLifetime.TriggerOnly);
            }
            if (commandName == "manage_gameobject" && action == "placement")
            {
                var preview = parameters["preview"];
                if (preview == null || preview.Type == JTokenType.Null || preview.Type == JTokenType.Boolean && (bool)preview
                    || preview.Type == JTokenType.String && string.Equals((string)preview, "true", StringComparison.OrdinalIgnoreCase))
                    return new ToolOperationPolicy(ToolOperationMode.SharedRead, ToolOperationLifetime.Command, "reviewed_preview");
                return Exclusive("conditional_mutation");
            }
            if (commandName == "manage_editor" && action == "play")
            {
                var wait = parameters["wait_until"];
                bool tracked = wait?.Type == JTokenType.String && ((string)wait == "scene_loaded" || (string)wait == "first_frame");
                return Exclusive("play_transition", tracked ? ToolOperationLifetime.TrackedJob : ToolOperationLifetime.TriggerOnly);
            }
            if (commandName == "manage_editor" && action == "stop")
                return Exclusive("play_transition", ToolOperationLifetime.TriggerOnly);
            return Rules.TryGetValue(commandName + "\n" + (action == null ? "0" : "1" + action), out var policy) ? policy : Exclusive("unreviewed_operation");
        }
    }
}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != expected:
            print("Native operation policy is stale. Run tools/generate_operation_policy.py")
            return 1
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(
        f"Verified operation policy v{POLICY_VERSION} ({len(POLICY_RULES)} reviewed rule groups)."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
